const NETWORK_KEYS = Object.keys(SOCIAL_NETWORKS);

function iconSvg(network) {
    const net = SOCIAL_NETWORKS[network] || SOCIAL_NETWORKS.website;
    return '<svg viewBox="0 0 24 24" width="20" height="20" fill="currentColor" aria-hidden="true"><path d="' + net.path + '"/></svg>';
}

export default class SocialIcons {
    static get toolbox() {
        return {
            title: 'Social icons',
            icon: '<svg width="17" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="18" cy="5" r="3"/><circle cx="6" cy="12" r="3"/><circle cx="18" cy="19" r="3"/><line x1="8.59" y1="13.51" x2="15.42" y2="17.49"/><line x1="15.41" y1="6.51" x2="8.59" y2="10.49"/></svg>',
        };
    }

    constructor({ data, block }) {
        const items = data && Array.isArray(data.items) ? data.items : [];
        this.items = items.length ? items : [{ network: 'x', url: '' }];
        this.shape = ['rounded', 'square', 'circle'].includes(data && data.shape) ? data.shape : 'rounded';
        this.style = ['brand', 'mono', 'outline'].includes(data && data.style) ? data.style : 'brand';
        this.size = ['sm', 'md', 'lg'].includes(data && data.size) ? data.size : 'md';
        this.align = ['left', 'center', 'right'].includes(data && data.align) ? data.align : 'left';
        this.block = block;
        this.wrapper = null;
    }

    /** Sidebar inspector: block-level presentation flags. */
    setProp(key, value) {
        if (key === 'shape' && ['rounded', 'square', 'circle'].includes(value)) {
            this.shape = value;
        } else if (key === 'style' && ['brand', 'mono', 'outline'].includes(value)) {
            this.style = value;
        } else if (key === 'size' && ['sm', 'md', 'lg'].includes(value)) {
            this.size = value;
        } else if (key === 'align' && ['left', 'center', 'right'].includes(value)) {
            this.align = value;
        }
        this.applyStyle();
        window.dispatchEvent(new CustomEvent('magna-blog:changed'));
    }

    applyStyle() {
        if (! this.wrapper) {
            return;
        }
        this.wrapper.dataset.shape = this.shape;
        this.wrapper.dataset.style = this.style;
        this.wrapper.dataset.size = this.size;
        this.wrapper.dataset.align = this.align;
    }

    render() {
        this.wrapper = document.createElement('div');
        this.wrapper.classList.add('magna-blog-social');

        this.list = document.createElement('div');
        this.list.classList.add('magna-blog-social__list');
        this.wrapper.append(this.list);
        this.items.forEach((item) => this.addRow(item));

        const add = document.createElement('button');
        add.type = 'button';
        add.classList.add('magna-blog-add');
        add.contentEditable = 'false';
        add.textContent = '+ Add icon';
        add.addEventListener('click', () => this.addRow({ network: 'x', url: '' }));
        this.wrapper.append(add);

        this.applyStyle();

        if (this.block && this.block.id) {
            window.magnaBlogBlocks = window.magnaBlogBlocks || {};
            window.magnaBlogBlocks[this.block.id] = this;
        }

        return this.wrapper;
    }

    addRow(item) {
        const row = document.createElement('div');
        row.classList.add('magna-blog-social__row');
        row.contentEditable = 'false';

        const preview = document.createElement('span');
        preview.classList.add('magna-blog-social__icon');

        const select = document.createElement('select');
        select.classList.add('magna-blog-social__net');
        NETWORK_KEYS.forEach((key) => {
            const opt = document.createElement('option');
            opt.value = key;
            opt.textContent = SOCIAL_NETWORKS[key].label;
            select.append(opt);
        });
        select.value = NETWORK_KEYS.includes(item.network) ? item.network : 'x';
        const paint = () => {
            preview.innerHTML = iconSvg(select.value);
            preview.style.color = SOCIAL_NETWORKS[select.value].color;
        };
        select.addEventListener('change', paint);
        paint();

        const url = document.createElement('input');
        url.type = 'url';
        url.classList.add('magna-blog-social__url', 'de-input');
        url.placeholder = 'https://…';
        url.value = item.url || '';

        const remove = document.createElement('button');
        remove.type = 'button';
        remove.classList.add('magna-blog-remove');
        remove.textContent = 'Remove';
        remove.addEventListener('click', () => row.remove());

        row.append(preview, select, url, remove);
        this.list.append(row);
    }

    save() {
        return {
            items: [...this.list.querySelectorAll('.magna-blog-social__row')].map((row) => ({
                network: row.querySelector('.magna-blog-social__net').value || 'website',
                url: (row.querySelector('.magna-blog-social__url').value || '').trim(),
            })).filter((item) => item.url !== ''),
            shape: this.shape,
            style: this.style,
            size: this.size,
            align: this.align,
        };
    }
}
